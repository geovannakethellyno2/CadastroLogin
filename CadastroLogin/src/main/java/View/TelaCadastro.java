    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        //CADASTRAR USUARIO NO BANCO DE DADOS
        Usuario pessoa = new Usuario(); //criando um objeto usuario
        pessoa.setNome(tfNome.getText().trim());
        pessoa.setCpf(ftCpf.getText().trim());
        pessoa.setEmail(tfEmail.getText().trim());
        pessoa.setTelefone(ftTelefone.getText().trim());
        pessoa.setDataNascimento(ftDataNascimento.getText().trim());
        
        pessoa.setEndereco(tfEndereco.getText().trim());
        
        String sn = new String (pfSenha.getPassword());
        String csn = new String (pfConfirmarSenha.getPassword());
         
        if (sn.equals(csn)){
                  pessoa.setSenha(new String (pfSenha.getPassword()));
        }else{
            JOptionPane.showMessageDialog(null,"As senhas não são iguais!");
        }
        
        
        pessoa.setSenha(new String(pfSenha.getPassword()));
        
        if(rbFeminino.isSelected()){
            pessoa.setSexo("feminino");
        }else if(rbMasculino.isSelected()){
            pessoa.setSexo("masculino");
        }else{ 
            pessoa.setSexo("não encontrado");
        }
        UsuarioController controler = new UsuarioController();
        try {
            controler.CadastrarUsuario(pessoa);            
           
        }catch (SQLException ex){  
           
        }
    }//GEN-LAST:event_btnCadastrarActionPerformed

